export const aiApi = {
  chat: (reelId, question, history) => api.post(`/ai/chat/${reelId}`, { question, history }),
  // Streams the tutor's answer: onToken(text) is called for every piece as it arrives. Resolves with the full text.
  // Uses fetch (axios can't stream in browsers). Throws Error(message); err.status is the HTTP status when known.
  chatStream: async (reelId, question, history, { onToken, signal } = {}) => {
    const res = await fetch(`/api/ai/chat/${reelId}/stream`, {
      method: "POST", signal,
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${localStorage.getItem("ter_token") || ""}` },
      body: JSON.stringify({ question, history }),
    });
    if (!res.ok || !res.body) {
      let msg = "The AI tutor is unavailable right now.";
      try { msg = (await res.json()).message || msg; } catch { /* not JSON */ }
      throw Object.assign(new Error(msg), { status: res.status });
    }
    const reader = res.body.getReader(), dec = new TextDecoder();
    let buf = "", full = "";
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      buf += dec.decode(value, { stream: true });
      let i;
      while ((i = buf.indexOf("\n\n")) !== -1) {
        const block = buf.slice(0, i); buf = buf.slice(i + 2);
        const isErr = /^event: error/m.test(block);
        const line = block.split("\n").find((l) => l.startsWith("data: "));
        if (!line) continue;
        const msg = JSON.parse(line.slice(6));
        if (isErr) throw Object.assign(new Error(msg.message || "The AI tutor stopped unexpectedly."), { status: 502, partial: full });
        if (msg.t) { full += msg.t; onToken?.(msg.t, full); }
      }
    }
    return full;
  },
  notes: (reelId) => api.post(`/ai/notes/${reelId}`),
  // source: "lesson" (curated, works without AI) | "ai" (generated by Gemini)
  startQuiz: (reelId, source, questionCount) => api.post(`/ai/quiz/${reelId}`, { source, questionCount }),
  submitQuiz: (reelId, sessionId, answers) => api.post(`/ai/quiz/${reelId}/submit`, { sessionId, answers }),
  captions: (reelId) => api.post(`/ai/captions/${reelId}`),
};

