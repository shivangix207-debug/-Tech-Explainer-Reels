export const uploadApi = {
  // file: a File from <input type="file">. Sent as multipart/form-data (field "video").
  video: (file, onProgress) => {
    const form = new FormData();
    form.append("video", file);
    return api.post("/upload/video", form, {
      onUploadProgress: (evt) => { if (onProgress && evt.total) onProgress(Math.round((evt.loaded / evt.total) * 100)); },
      timeout: 0,
    });
  },
};
